-- Support tickets join bugs and suggestions in the same inbox: a third report type, with the kind
-- of help needed, and a sequential ticket number shown to the customer (#1001, #1002...).
ALTER TABLE bug_reports DROP CONSTRAINT bug_reports_report_type_check;
ALTER TABLE bug_reports
  ADD CONSTRAINT bug_reports_report_type_check CHECK (report_type IN ('bug', 'suggestion', 'support'));

ALTER TABLE bug_reports ADD COLUMN support_category TEXT;

-- Existing reports are numbered too, in the order the identity fills them.
ALTER TABLE bug_reports ADD COLUMN ticket_number BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001);
CREATE UNIQUE INDEX bug_reports_ticket_number_idx ON bug_reports (ticket_number);
