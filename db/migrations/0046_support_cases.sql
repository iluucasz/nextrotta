-- Cases ("casos") of the NextRotta team, in the way of a service console: a conversation that was not settled on the spot becomes a
-- case, with a status, a priority, an owner (the attendant in charge) and notes, to be worked on later. A case is the team's own
-- record (it may concern someone who is not a customer yet), apart from the tickets the customers open in their own system.
-- Nothing here is ever deleted: a case ends as "resolved" and keeps its history.
CREATE TABLE support_cases (
  id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  case_number      BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 5001),
  subject          TEXT NOT NULL,
  description      TEXT NOT NULL DEFAULT '',
  status           TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'working', 'waiting', 'resolved')),
  priority         TEXT NOT NULL DEFAULT 'medium' CHECK (priority IN ('low', 'medium', 'high', 'critical')),
  origin           TEXT NOT NULL CHECK (origin IN ('livechat', 'whatsapp', 'manual')),
  organization_id  UUID REFERENCES organizations (id),
  contact_name     TEXT,
  contact_phone    TEXT,
  -- The attendant in charge (null = nobody yet).
  owner_id         UUID REFERENCES users (id),
  created_by       UUID NOT NULL REFERENCES users (id),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_at      TIMESTAMPTZ
);
CREATE UNIQUE INDEX support_cases_number_idx ON support_cases (case_number);
CREATE INDEX support_cases_status_idx ON support_cases (status, updated_at DESC);
CREATE INDEX support_cases_owner_idx ON support_cases (owner_id) WHERE owner_id IS NOT NULL;
CREATE INDEX support_cases_phone_idx ON support_cases (contact_phone) WHERE contact_phone IS NOT NULL;

-- The history of a case (what a service console calls activities): who did what and when, and the internal notes.
CREATE TABLE support_case_events (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  case_id    UUID NOT NULL REFERENCES support_cases (id),
  kind       TEXT NOT NULL CHECK (kind IN ('created', 'status', 'priority', 'owner', 'subject', 'note', 'conversation')),
  -- Null when the system did it.
  author_id  UUID REFERENCES users (id),
  body       TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX support_case_events_case_idx ON support_case_events (case_id, created_at);

-- The case a conversation was turned into (a case may gather several conversations: the customer writes again).
ALTER TABLE livechat_conversations ADD COLUMN case_id UUID REFERENCES support_cases (id);
CREATE INDEX livechat_conversations_case_idx ON livechat_conversations (case_id) WHERE case_id IS NOT NULL;
